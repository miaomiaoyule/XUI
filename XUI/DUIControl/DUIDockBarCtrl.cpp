enDuiDockBarEffectType CDUIDockBarCtrl::GetEffectType()
{
	return (enDuiDockBarEffectType)m_AttributeEffectType.GetCurSelItem();
}

void CDUIDockBarCtrl::SetEffectType(enDuiDockBarEffectType EffectType)
{
	if (EffectType == GetEffectType()) return;

	m_AttributeEffectType.SelectItem(EffectType);

	return;
}

float CDUIDockBarCtrl::GetScaleMax()
{
	float fScaleMax = m_AttributeScaleMax.GetValue();

	return max(1.0f, fScaleMax);
}

void CDUIDockBarCtrl::SetScaleMax(float fScaleMax)
{
	if (fScaleMax <= 0 || fScaleMax == m_AttributeScaleMax.GetValue()) return;

	m_AttributeScaleMax.SetValue(fScaleMax);

	return;
}

int CDUIDockBarCtrl::GetEffectRange()
{
	return m_AttributeEffectRange.GetValue();
}

void CDUIDockBarCtrl::SetEffectRange(int nRange)
{
	if (nRange == GetEffectRange()) return;

	m_AttributeEffectRange.SetValue(nRange);

	return;
}

float CDUIDockBarCtrl::GetReflectionRatio()
{
	float fRatio = m_AttributeReflectionRatio.GetValue();

	//the reflection is generated by CDUIRenderEngine::GenerateReflectionBitmap,
	//its height is the icon height * ratio, the item height = icon * (1 + ratio)
	return max(0.0f, fRatio);
}

void CDUIDockBarCtrl::SetReflectionRatio(float fRatio)
{
	if (fRatio < 0.0f) fRatio = 0.0f;
	if (fRatio == GetReflectionRatio()) return;

	m_AttributeReflectionRatio.SetValue(fRatio);

	Invalidate();

	return;
}

bool CDUIDockBarCtrl::OnDuiMouseMove(const CDUIPoint &pt, const DuiMessage &Msg)
{
	bool bRes = __super::OnDuiMouseMove(pt, Msg);

	if (DockBarEffect_MouseMove == GetEffectType() && m_vecItemBaseSize.size() > 0)
	{
		m_ptMousePos = pt;

		StartEffect();
		PerformMouseMoveEffect();
	}

	return bRes;
}

void CDUIDockBarCtrl::OnDuiMouseLeave(const CDUIPoint &pt, const DuiMessage &Msg)
{
	__super::OnDuiMouseLeave(pt, Msg);

	StopEffect();

	return;
}

void CDUIDockBarCtrl::OnDuiWndManagerDetach()
{
	StopEffect();

	__super::OnDuiWndManagerDetach();

	return;
}

void CDUIDockBarCtrl::InitProperty()
{
	__super::InitProperty();

	//dock bar
	DuiCreateGroupAttribute(m_AttributeGroupDockBar, _T("DockBar"));
	DuiCreateAttribute(m_AttributeEffectType, _T("EffectType"), _T(""), m_AttributeGroupDockBar);
	DuiCreateAttribute(m_AttributeScaleMax, _T("ScaleMax"), _T(""), m_AttributeGroupDockBar);
	DuiCreateAttribute(m_AttributeEffectRange, _T("EffectRange"), _T(""), m_AttributeGroupDockBar);
	DuiCreateAttribute(m_AttributeReflectionRatio, _T("ReflectionRatio"), _T(""), m_AttributeGroupDockBar);

	return;
}

void CDUIDockBarCtrl::InitComplete()
{
	__super::InitComplete();

	DuiInitAttriVisible(m_AttributeGroupListType, false);

	//dock bar only support the horizontal tile layout
	SwitchListViewType(ListView_TileH);

	//item notify is send by list view self(pNotifyCtrl == this), so dock bar must listen self
	RegisterControlCallBack(this);

	return;
}

void CDUIDockBarCtrl::OnItemMouseMove(CDUIControlBase *pControl, const DuiNotify &Notify)
{
	if (DockBarEffect_MouseMove == GetEffectType())
	{
		m_ptMousePos = Notify.ptMouse;

		StartEffect();
		PerformMouseMoveEffect();
	}

	return;
}

void CDUIDockBarCtrl::OnItemMouseEnter(CDUIControlBase *pControl, const DuiNotify &Notify)
{
	if (DockBarEffect_None == GetEffectType()) return;

	return;
}

void CDUIDockBarCtrl::StartEffect()
{
	//the item is dragging, the effect is resumed after the drag is finished
	if (IsAnimateDraging() || NULL == m_pWndOwner) return;

	//base size
	if (m_vecItemBaseSize.size() > 0) return;
	int nCount = GetChildCount();
	m_vecItemBaseSize.assign(nCount, CDUISize());
	for (int n = 0; n < nCount; n++)
	{
		CDUIListItemCtrl *pItem = GetChildAt(n);
		if (NULL == pItem) continue;

		m_vecItemBaseSize[n] = { pItem->GetFixedWidth(), pItem->GetFixedHeight() };
	}

	return;
}

void CDUIDockBarCtrl::StopEffect()
{
	//restore size
	for (int n = 0; n < GetChildCount() && n < m_vecItemBaseSize.size(); n++)
	{
		CDUIListItemCtrl *pItem = GetChildAt(n);
		if (NULL == pItem) continue;

		pItem->SetFixedWidth(DuiDpiScaleBackCtrl(m_vecItemBaseSize[n].cx));
		pItem->SetFixedHeight(DuiDpiScaleBackCtrl(m_vecItemBaseSize[n].cy));
	}

	m_vecItemBaseSize.clear();

	RefreshView();

	return;
}

void CDUIDockBarCtrl::PerformMouseMoveEffect()
{
	if (GetChildCount() <= 0 || m_vecItemBaseSize.empty()) return;

	CDUIRect rcItemRange = GetLayoutRangeOfItem();
	CDUISize szBase = m_vecItemBaseSize[0];
	int nEffectRange = GetEffectRange();
	float fScaleMax = GetScaleMax();
	float fScaleEvery = (fScaleMax - 1) / (nEffectRange + 1);
	float fScaleTotal = 0;
	for (int n = 0; n < nEffectRange; n++)
	{
		fScaleTotal += 1;
		fScaleTotal += (fScaleEvery * (n + 1));
	}

	fScaleTotal *= 2;
	fScaleTotal += fScaleMax;
	int nWidthEffectSize = szBase.cx * fScaleTotal + GetChildPaddingH() * nEffectRange * 2;
	int nWidthEffectTotal = 0;
	CDUIRect rcEffectRange;
	rcEffectRange.left = m_ptMousePos.x - nWidthEffectSize / 2;
	rcEffectRange.right = m_ptMousePos.x + nWidthEffectSize / 2;
	rcEffectRange.top = rcItemRange.top;
	rcEffectRange.bottom = rcItemRange.bottom;
	int nLengthStep = rcEffectRange.GetWidth() / 2;
	std::deque<tagDuiDockBarItem> queEffectItem;
	for (int n = 0; n < GetChildCount() && n < m_vecItemBaseSize.size(); n++)
	{
		CDUIListItemCtrl *pItem = GetChildAt(n);
		if (NULL == pItem) continue;

		CDUIRect rcItem = pItem->GetAbsoluteRect();
		if (false == ::IntersectRect(&rcItem, &rcItem, &rcEffectRange))
		{
			pItem->SetFixedWidth(m_vecItemBaseSize[n].cx);
			pItem->SetFixedHeight(m_vecItemBaseSize[n].cy);

			continue;
		}

		int nCenterX = rcItem.left + rcItem.GetWidth() / 2;
		float fScale = (1.0f - abs(nCenterX - m_ptMousePos.x) * 1.0f / nLengthStep);
		fScale = 1.0f + (fScale * (fScaleMax - 1.0f));
		CDUISize szEffect;
		szEffect.cx = (m_vecItemBaseSize[n].cx * fScale);
		szEffect.cy = (m_vecItemBaseSize[n].cy * fScale);
		nWidthEffectTotal += (szEffect.cx);

		tagDuiDockBarItem DockBarItem;
		DockBarItem.pItem = pItem;
		DockBarItem.szEffect = szEffect;
		queEffectItem.push_back(DockBarItem);
	}
	while (queEffectItem.size() > nEffectRange * 2 + 1)
	{
		tagDuiDockBarItem EffectItemFront = queEffectItem.front();
		tagDuiDockBarItem EffectItemBack = queEffectItem.back();
		CDUIRect rcItemFront = EffectItemFront.pItem->GetAbsoluteRect();
		CDUIRect rcItemBack = EffectItemBack.pItem->GetAbsoluteRect();
		if (abs(rcItemFront.left + rcItemFront.GetWidth() / 2 - m_ptMousePos.x)
			>= abs(rcItemBack.left + rcItemBack.GetWidth() / 2 - m_ptMousePos.x))
		{
			nWidthEffectTotal -= (EffectItemFront.szEffect.cx);
			nWidthEffectSize -= EffectItemFront.szEffect.cx - szBase.cx;
			EffectItemFront.pItem->SetFixedWidth(DuiDpiScaleBackCtrl(EffectItemFront.szEffect.cx));
			EffectItemFront.pItem->SetFixedHeight(DuiDpiScaleBackCtrl(EffectItemFront.szEffect.cy));
			queEffectItem.pop_front();
		}
		else
		{
			nWidthEffectTotal -= (EffectItemBack.szEffect.cx);
			nWidthEffectSize -= EffectItemBack.szEffect.cx - szBase.cx;
			EffectItemBack.pItem->SetFixedWidth(DuiDpiScaleBackCtrl(EffectItemBack.szEffect.cx));
			EffectItemBack.pItem->SetFixedHeight(DuiDpiScaleBackCtrl(EffectItemBack.szEffect.cy));
			queEffectItem.pop_back();
		}
	}
	if (queEffectItem.size() == nEffectRange * 2 + 1)
	{
		int nWidthSurplus = abs(nWidthEffectSize - nWidthEffectTotal);
		int nWidthEvery = nWidthSurplus / queEffectItem.size();
		nWidthSurplus = nWidthSurplus % queEffectItem.size();
		for (auto EffectItem : queEffectItem)
		{
			if (NULL == EffectItem.pItem) continue;

			int nWidth = EffectItem.szEffect.cx + (nWidthEvery);
			nWidth += (nWidthSurplus > 0 ? (1) : 0);
			nWidthSurplus--;
			nWidthSurplus = max(0, nWidthSurplus);
			EffectItem.pItem->SetFixedWidth(DuiDpiScaleBackCtrl(nWidth));
			EffectItem.pItem->SetFixedHeight(DuiDpiScaleBackCtrl(EffectItem.szEffect.cy));
		}
	}

	return;
}
